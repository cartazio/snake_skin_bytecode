@dataclass(frozen=True, slots=True)
class UnknownOpcode:
    """Raw identity for an opcode outside the closed known set."""

    opname: str
    raw_code: int | None


OpcodeIdentity = KnownOpcode | UnknownOpcode


def identify_opcode(opname: str, raw_code: int | None = None) -> OpcodeIdentity:
    """Classify raw CPython opcode identity without claiming semantic support."""
    try:
        return KnownOpcode(opname)
    except ValueError:
        return UnknownOpcode(opname=opname, raw_code=raw_code)
